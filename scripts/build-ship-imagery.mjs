import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(await fs.readFile(path.join(root, 'data/ship-imagery.json'), 'utf8'));
const catalog = JSON.parse(await fs.readFile(path.join(root, 'data/canonical/presentation-ships.json'), 'utf8'));
const seen = new Set();
const runtime = {};
if (manifest.schema !== 'volt-ship-imagery/v1') throw Error('Unsupported imagery schema');
for (const entry of manifest.records) {
    const ship = catalog.records.find((item) => item.id === entry.id);
    if (!ship || seen.has(entry.id) || entry.reviewStatus !== 'verified') throw Error(`Unreviewed or duplicate ship: ${entry.id}`);
    seen.add(entry.id);
    if (entry.productName !== ship.name || !/^\d{4}-\d{2}-\d{2}$/.test(entry.reviewedAt)) throw Error(`Product review mismatch: ${entry.id}`);
    for (const key of ['sourcePage', 'sourceUrl']) {
        const url = new URL(entry[key]);
        if (url.protocol !== 'https:' || url.hostname !== 'robertsspaceindustries.com' || url.username || url.password) throw Error(`Invalid official source: ${entry.id}`);
    }
    if (new URL(entry.sourcePage).pathname.replace(/^\/en\//, '/') !== new URL(ship.rsiUrl).pathname.replace(/^\/en\//, '/')) throw Error(`Wrong product page: ${entry.id}`);
    if (!entry.altKo || !entry.altEn) throw Error(`Missing alternative text: ${entry.id}`);
    for (const kind of ['thumbnail', 'detail']) {
        const asset = entry[kind];
        if (asset.path !== `/assets/images/ships/${entry.id}-${kind}.webp`) throw Error(`Invalid local image path: ${entry.id}`);
        if (!(asset.width > 0 && asset.height > 0 && asset.width <= entry.original.width && asset.height <= entry.original.height)) throw Error(`Invalid image dimensions: ${entry.id}`);
        const bytes = await fs.readFile(path.join(root, asset.path.slice(1)));
        if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP' || bytes.length !== asset.bytes || createHash('sha256').update(bytes).digest('hex') !== asset.sha256) throw Error(`Image integrity mismatch: ${entry.id}`);
    }
    runtime[entry.id] = { thumbnail: entry.thumbnail, detail: entry.detail, sourcePage: entry.sourcePage, altKo: entry.altKo, altEn: entry.altEn };
}
const output = `/* Generated by scripts/build-ship-imagery.mjs. Edit data/ship-imagery.json. */\n(function () {\n    'use strict';\n    const images = ${JSON.stringify(runtime, null, 4)};\n    for (const entry of Object.values(images)) {\n        Object.freeze(entry.thumbnail);\n        Object.freeze(entry.detail);\n        Object.freeze(entry);\n    }\n    Object.freeze(images);\n    window.VOLT_SHIP_IMAGERY = Object.freeze({\n        get(id) { return Object.hasOwn(images, id) ? images[id] : null; },\n    });\n})();\n`;
const target = path.join(root, 'js/ship-imagery.js');
if (process.argv.includes('--verify')) {
    if ((await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== output) throw Error('Ship imagery runtime is stale; rebuild it');
} else await fs.writeFile(target, output);
console.log(`Verified ${seen.size} exact ship image mappings and ${seen.size * 2} local assets.`);
