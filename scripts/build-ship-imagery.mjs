import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(await fs.readFile(path.join(root, 'data/ship-imagery.json'), 'utf8'));
const presentation = JSON.parse(await fs.readFile(path.join(root, 'data/canonical/presentation-ships.json'), 'utf8'));
const official = JSON.parse(await fs.readFile(path.join(root, 'data/canonical/ships-rsi-official.json'), 'utf8'));
const catalog = [...presentation.records, ...official.records];
const review = JSON.parse(await fs.readFile(path.join(root, 'data/ship-imagery-review.json'), 'utf8'));
const reviews = new Map(review.records.map((entry) => [entry.id, entry]));
const seen = new Set();
const sourceHashes = new Set();
const runtime = {};
if (manifest.schema !== 'volt-ship-imagery/v1') throw Error('Unsupported imagery schema');
if (review.schema !== 'volt-ship-imagery-review/v1' || reviews.size !== review.records.length || review.records.some((entry) => !['verified', 'held'].includes(entry.status))) throw Error('Invalid image review registry');
if (review.verifiedCount !== manifest.records.length || review.heldCount !== review.records.filter((entry) => entry.status === 'held').length || review.catalogCountAtReview !== review.records.length) throw Error('Invalid reviewed coverage totals');
for (const entry of manifest.records) {
    const ship = catalog.find((item) => item.id === entry.id);
    const approval = reviews.get(entry.id);
    if (!ship || seen.has(entry.id) || entry.reviewStatus !== 'verified') throw Error(`Unreviewed or duplicate ship: ${entry.id}`);
    seen.add(entry.id);
    if (sourceHashes.has(entry.original.sha256)) throw Error(`Original photo reused across models: ${entry.id}`);
    sourceHashes.add(entry.original.sha256);
    if (entry.productName !== ship.name || !/^\d{4}-\d{2}-\d{2}$/.test(entry.reviewedAt)) throw Error(`Product review mismatch: ${entry.id}`);
    if (approval?.status !== 'verified' || approval.catalogName !== ship.name || !approval.officialProductName || approval.sourcePage !== entry.sourcePage || approval.sourceUrl !== entry.sourceUrl || approval.originalSha256 !== entry.original.sha256 || !/^[a-f0-9]{64}$/.test(approval.pageSha256)) throw Error(`Photo does not match reviewed product: ${entry.id}`);
    for (const key of ['sourcePage', 'sourceUrl']) {
        const url = new URL(entry[key]);
        if (url.protocol !== 'https:' || url.hostname !== 'robertsspaceindustries.com' || url.username || url.password) throw Error(`Invalid official source: ${entry.id}`);
    }
    if (!/^\/(?:en\/)?pledge\/ships\/[^/]+\/[^/]+$/.test(new URL(entry.sourcePage).pathname)) throw Error(`Invalid reviewed product page: ${entry.id}`);
    if (!entry.altKo || !entry.altEn?.startsWith(ship.name.trim())) throw Error(`Missing or mismatched alternative text: ${entry.id}`);
    for (const kind of ['thumbnail', 'detail']) {
        const asset = entry[kind];
        if (asset.path !== `/assets/images/ships/${entry.id}-${kind}.webp`) throw Error(`Invalid local image path: ${entry.id}`);
        if (!(asset.width > 0 && asset.height > 0 && asset.width <= entry.original.width && asset.height <= entry.original.height)) throw Error(`Invalid image dimensions: ${entry.id}`);
        const bytes = await fs.readFile(path.join(root, asset.path.slice(1)));
        if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP' || bytes.length !== asset.bytes || createHash('sha256').update(bytes).digest('hex') !== asset.sha256) throw Error(`Image integrity mismatch: ${entry.id}`);
        // All approved derivatives are RGB lossy WebP (VP8); verify encoded dimensions too.
        if (bytes.toString('ascii', 12, 16) !== 'VP8 ' || (bytes.readUInt16LE(26) & 0x3fff) !== asset.width || (bytes.readUInt16LE(28) & 0x3fff) !== asset.height) throw Error(`Encoded image dimensions mismatch: ${entry.id}`);
    }
    const displayAsset = ({ path: assetPath, width, height }) => ({ path: assetPath, width, height });
    runtime[entry.id] = { thumbnail: displayAsset(entry.thumbnail), detail: displayAsset(entry.detail), sourcePage: entry.sourcePage, altKo: entry.altKo, altEn: entry.altEn };
}
for (const approval of review.records) {
    if ((approval.status === 'verified') !== seen.has(approval.id)) throw Error(`Reviewed coverage mismatch: ${approval.id}`);
}
const output = `/* Generated by scripts/build-ship-imagery.mjs. Edit data/ship-imagery.json. */\n(function () {\n    'use strict';\n    const images = ${JSON.stringify(runtime)};\n    for (const entry of Object.values(images)) {\n        Object.freeze(entry.thumbnail);\n        Object.freeze(entry.detail);\n        Object.freeze(entry);\n    }\n    Object.freeze(images);\n    window.VOLT_SHIP_IMAGERY = Object.freeze({\n        get(id) { return Object.hasOwn(images, id) ? images[id] : null; },\n    });\n})();\n`;
const target = path.join(root, 'js/ship-imagery.js');
if (process.argv.includes('--verify')) {
    if ((await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== output) throw Error('Ship imagery runtime is stale; rebuild it');
} else await fs.writeFile(target, output);
console.log(`Verified ${seen.size} exact ship image mappings and ${seen.size * 2} local assets.`);
