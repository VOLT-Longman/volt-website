// Pages' bundled Wrangler cannot parse JSON import attributes. Generate only
// the release identifier as plain ESM, without duplicating or changing game data.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = new URL('../../functions/_shared/gear-model-version.js', import.meta.url);
export function syncModelVersion(version, verify = false) {
  if (!/^[\w.-]{1,40}$/.test(version || '')) throw new Error('Invalid model assetVersion');
  const source = `// Generated by scripts/gear/sync-model-version.mjs from data/gear/models.json.\nexport const gearModelVersion = '${version}';\n`;
  if (verify) {
    if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) throw new Error('Model version is stale. Run node scripts/gear/sync-model-version.mjs');
  } else writeFileSync(target, source);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const index = JSON.parse(readFileSync(new URL('../../data/gear/models.json', import.meta.url), 'utf8'));
  syncModelVersion(index.assetVersion, process.argv.includes('--verify'));
  console.log(`Model server version matches models.json: ${index.assetVersion}`);
}
