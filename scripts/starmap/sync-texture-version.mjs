// Pages' bundled Wrangler cannot parse JSON import attributes. Generate only
// the release identifier as plain ESM (same reason as scripts/gear/sync-model-version.mjs).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = new URL('../../functions/_shared/starmap-texture-version.js', import.meta.url);
export function syncTextureVersion(version, verify = false) {
  if (!/^[\w.-]{1,40}$/.test(version || '')) throw new Error('Invalid star-map texture assetVersion');
  const source = `// Generated by scripts/starmap/sync-texture-version.mjs from data/starmap/textures.json.\nexport const starmapTextureVersion = '${version}';\n`;
  if (verify) {
    if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) throw new Error('Star-map texture version is stale. Run node scripts/starmap/sync-texture-version.mjs');
  } else writeFileSync(target, source);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const index = JSON.parse(readFileSync(new URL('../../data/starmap/textures.json', import.meta.url), 'utf8'));
  syncTextureVersion(index.assetVersion, process.argv.includes('--verify'));
  console.log(`Star-map texture server version matches textures.json: ${index.assetVersion}`);
}
